def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--patch", help="Emit an apply_patch add-file patch for this path")
    parser.add_argument("--quad", action="store_true", help="Export the certified 985-cycle quad-table variant")
    parser.add_argument("--early", action="store_true", help="Export the certified 984-cycle early-selection variant")
    parser.add_argument("--prefix", action="store_true", help="Export the certified 983-cycle prefix-compression variant")
    args = parser.parse_args()
    if sum((args.quad, args.early, args.prefix)) > 1:
        parser.error("choose one variant")
    source = render(quad=args.quad, early=args.early, prefix=args.prefix)
    if args.patch:
        print("*** Begin Patch\n*** Add File: " + args.patch)
        print("\n".join("+" + line for line in source.splitlines()))
        print("*** End Patch")
    else:
        print(source, end="")


if __name__ == "__main__":
    main()
